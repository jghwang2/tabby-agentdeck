const assert = require('node:assert/strict'), fs = require('fs'), ts = require('typescript')
require.extensions['.ts'] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), {
    compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 },
}).outputText, f)
const { AgentLifecycle, AGENT_IDLE_TIMEOUT_MS: ttl } = require('../src/agentLifecycle.ts')
const a = new AgentLifecycle(), b = new AgentLifecycle(), now = Date.now()
const event = (id, action = 'active', at = now) => ({ id, action, ts: at, type: 'general-purpose' })
a.accept(event('first')); a.accept(event('second')); a.accept(event('first'))
assert.equal(a.active().length, 2, 'duplicate hooks are idempotent')
a.accept(event('first', 'stop', now + 1)); a.accept(event('second', 'stop', now + 1))
assert.equal(a.active().length, 0)
a.accept(event('later', 'active', now + 2)); a.accept(event('first', 'active', now + 2))
assert.equal(a.active().length, 2, 'later generation and resumed agent are both counted')
a.accept(event('first', 'stop', now + 1))
assert.equal(a.active().length, 2, 'late stop cannot erase a more recent heartbeat')
assert.equal(a.active(now + 2 + ttl - 1).length, 2)
assert.equal(a.active(now + 2 + ttl).length, 0, 'expires at fifteen minutes, not before')
a.accept(event('first', 'active', now + 3))
assert.equal(a.active(now + 2 + ttl).length, 1, 'only this agent receives the heartbeat')
b.accept(event('first')); a.accept(event('first', 'stop', now + 4))
assert.equal(b.active().length, 1, 'same id in a different parent is independent')
a.accept(event('never-started', 'stop')); assert.ok(!a.active().some(e => e.id === 'never-started'))
assert.equal(a.accept(event('../invalid')), false)
assert.equal(a.accept(event('future', 'active', now + 120000)), false)
assert.equal(a.accept(event('bad-clock', 'active', NaN)), false)
a.accept(event('tie', 'stop')); a.accept(event('tie'))
assert.ok(!a.active().some(e => e.id === 'tie'), 'stop wins equal timestamp')
console.log('PASS agent lifecycle: later generation, resume, timeout, isolation, replay and out-of-order events')
